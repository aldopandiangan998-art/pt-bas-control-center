function mkNomorRO() {
  return `RO-${new Date().getFullYear()}-${String(Date.now()).slice(-4)}`;
}

function createItemFromMaterial(mat, existingId = null, defaultSatuan = 'm³') {
  if (!mat) {
    return {
      id: existingId || `item-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
      materialId: '',
      nama: '',
      itemType: ITEM_TYPES.MATERIAL,
      category: 'Curah',
      satuan: defaultSatuan || 'm³',
      kuantitas: '',
      hargaBeli: 0,
      hargaJual: 0,
      pphRate: 2.0,
      isAutoGenerated: false,
    };
  }
  const type = getItemType(mat);
  return {
    id: existingId || `item-${Date.now()}-${Math.random().toString(36).slice(2, 7)}`,
    materialId: mat.id || '',
    nama: mat.name || mat.nama || '',
    itemType: type,
    category: mat.category || (type === ITEM_TYPES.JASA_ANGKUT ? 'Jasa' : 'Curah'),
    satuan: type === ITEM_TYPES.JASA_ANGKUT ? '' : (mat.satuan || mat.defaultUnit || defaultSatuan || 'm³'),
    kuantitas: '', // User only enters quantity!
    hargaBeli: Number(mat.beli) || 0, // Auto-populated from database
    hargaJual: Number(mat.jual) || 0, // Auto-populated from database
    pphRate: Number(mat.pphRate) || 2.0,
    isAutoGenerated: false,
    linkedMaterialId: mat.materialId || 'mat-8',
  };
}

function createAutoJasaAngkutItem(parentMatItem, allMats = []) {
  const targetMatId = parentMatItem.materialId || parentMatItem.id || 'mat-8';
  const parentName = (parentMatItem.nama || parentMatItem.name || '').toUpperCase().trim();

  const targetJa =
    allMats.find((m) => getItemType(m) === ITEM_TYPES.JASA_ANGKUT && m.materialId === targetMatId) ||
    allMats.find((m) => {
      if (getItemType(m) !== ITEM_TYPES.JASA_ANGKUT) return false;
      const jName = (m.name || m.nama || '').toUpperCase();
      return jName.includes(`(${parentName})`) || (parentName && jName.includes(parentName));
    }) ||
    allMats.find((m) => (m.name || m.nama || '').toUpperCase() === 'JASA ANGKUT') ||
    allMats.find((m) => getItemType(m) === ITEM_TYPES.JASA_ANGKUT) || {
      id: 'mat-3-generic',
      name: 'JASA ANGKUT',
      category: 'Jasa',
      satuan: '',
      defaultUnit: '',
      beli: 20408,
      jual: 20408,
      pphRate: 2.0,
    };

  return {
    id: `auto-ja-${parentMatItem.id}`,
    parentItemId: parentMatItem.id,
    isAutoGenerated: true,
    itemType: ITEM_TYPES.JASA_ANGKUT,
    materialId: targetJa.id,
    nama: targetJa.name || targetJa.nama,
    category: targetJa.category || 'Jasa',
    satuan: '', // Jasa Angkut tanpa satuan
    kuantitas: parentMatItem.kuantitas || '',
    hargaBeli: Number(targetJa.beli) || 0,
    hargaJual: Number(targetJa.jual) || 0,
    pphRate: Number(targetJa.pphRate) || 2.0,
  };
}

