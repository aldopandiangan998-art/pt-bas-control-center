const formatNumber = (num) => {
  const val = Number(num) || 0;
  return val.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
};

function formatPoNumber(poNum) {
  if (!poNum) return 'PO: -';
  const clean = String(poNum).replace(/^PO:\s*/i, '').trim();
  return `PO: ${clean}`;
}

