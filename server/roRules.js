/**
 * roRules.js - Centralized Business Rules for Receive Order (RO) Items (Backend)
 *
 * Rules:
 * 1. JASA ANGKUT + MATERIAL:
 *    - Item Material (dengan satuan) yang dipilih dan kuantitas diinput pada baris Material.
 *    - Sistem otomatis membuat baris Jasa Angkut (tanpa satuan) yang kuantitasnya mengikuti kuantitas Material.
 * 2. MATERIAL SAJA:
 *    - Hanya item Material yang boleh ditambahkan (Jasa Angkut dilarang).
 * 3. JASA ANGKUT SAJA:
 *    - Hanya item Jasa Angkut yang boleh ditambahkan (Material dilarang).
 */

export const ITEM_TYPES = {
  MATERIAL: 'MATERIAL',
  JASA_ANGKUT: 'JASA_ANGKUT',
};

export const RO_TYPES = {
  JASA_ANGKUT_MATERIAL: 'JASA ANGKUT + MATERIAL',
  MATERIAL_SAJA: 'MATERIAL SAJA',
  JASA_ANGKUT_SAJA: 'JASA ANGKUT SAJA',
};

export const RO_ITEM_RULES = {
  [RO_TYPES.JASA_ANGKUT_MATERIAL]: {
    allowedItemTypes: [ITEM_TYPES.MATERIAL],
    autoCreateJasaAngkut: true,
    autoCreateMaterial: false,
    label: 'Jasa Angkut + Material',
    description: 'Item Material dipilih; item Jasa Angkut dibuat otomatis oleh sistem dan mengikuti kuantitas material',
  },
  [RO_TYPES.MATERIAL_SAJA]: {
    allowedItemTypes: [ITEM_TYPES.MATERIAL],
    autoCreateJasaAngkut: false,
    autoCreateMaterial: false,
    label: 'Material Saja',
    description: 'Hanya item Material yang dapat ditambahkan',
  },
  [RO_TYPES.JASA_ANGKUT_SAJA]: {
    allowedItemTypes: [ITEM_TYPES.JASA_ANGKUT],
    autoCreateJasaAngkut: false,
    autoCreateMaterial: false,
    label: 'Jasa Angkut Saja',
    description: 'Hanya item Jasa Angkut yang dapat ditambahkan',
  },
};

/**
 * Normalizes input string to canonical RO_TYPES value
 */
export function normalizeRoType(roType) {
  if (!roType) return RO_TYPES.JASA_ANGKUT_MATERIAL;
  const upper = String(roType).trim().toUpperCase();
  if (upper.includes('JASA ANGKUT + MATERIAL') || upper === 'JASA_ANGKUT_MATERIAL') {
    return RO_TYPES.JASA_ANGKUT_MATERIAL;
  }
  if (upper.includes('MATERIAL SAJA') || upper === 'MATERIAL_SAJA') {
    return RO_TYPES.MATERIAL_SAJA;
  }
  if (upper.includes('JASA ANGKUT SAJA') || upper === 'JASA_ANGKUT_SAJA') {
    return RO_TYPES.JASA_ANGKUT_SAJA;
  }
  return roType;
}

/**
 * Classifies an item into ITEM_TYPES.MATERIAL or ITEM_TYPES.JASA_ANGKUT
 */
export function getItemType(item) {
  if (!item) return ITEM_TYPES.MATERIAL;
  if (item.itemType === ITEM_TYPES.JASA_ANGKUT || item.itemType === ITEM_TYPES.MATERIAL) {
    return item.itemType;
  }
  const cat = String(item.category || '').toLowerCase();
  const name = String(item.name || item.nama || '').toUpperCase();
  if (cat === 'jasa' || name.includes('JASA ANGKUT') || name.includes('ANGKUT')) {
    return ITEM_TYPES.JASA_ANGKUT;
  }
  return ITEM_TYPES.MATERIAL;
}

/**
 * Returns allowed item types for a given RO type
 */
export function getAllowedItemTypes(roType) {
  const norm = normalizeRoType(roType);
  return RO_ITEM_RULES[norm]?.allowedItemTypes || [ITEM_TYPES.MATERIAL, ITEM_TYPES.JASA_ANGKUT];
}

/**
 * Returns whether the RO type requires automatic generation of Jasa Angkut items
 */
export function shouldAutoCreateJasaAngkut(roType) {
  const norm = normalizeRoType(roType);
  return Boolean(RO_ITEM_RULES[norm]?.autoCreateJasaAngkut);
}

/**
 * Backward compatibility alias
 */
export function shouldAutoCreateMaterial(roType) {
  return shouldAutoCreateJasaAngkut(roType);
}

/**
 * Checks if a specific item is allowed under the given RO type
 */
export function isItemAllowed(roType, item) {
  const allowed = getAllowedItemTypes(roType);
  const type = getItemType(item);
  return allowed.includes(type);
}

/**
 * Validates a list of items against RO rules.
 * Returns { isValid: boolean, error: string | null }
 */
export function validateRoItems(roType, items = []) {
  const norm = normalizeRoType(roType);
  if (!Array.isArray(items) || items.length === 0) {
    return { isValid: false, error: 'Daftar item tidak boleh kosong' };
  }

  if (norm === RO_TYPES.MATERIAL_SAJA) {
    const hasJasa = items.some((it) => getItemType(it) === ITEM_TYPES.JASA_ANGKUT);
    if (hasJasa) {
      return {
        isValid: false,
        error: 'Item Jasa Angkut tidak diizinkan pada RO jenis Material Saja',
      };
    }
  }

  if (norm === RO_TYPES.JASA_ANGKUT_SAJA) {
    const hasMaterial = items.some((it) => getItemType(it) === ITEM_TYPES.MATERIAL);
    if (hasMaterial) {
      return {
        isValid: false,
        error: 'Item Material tidak diizinkan pada RO jenis Jasa Angkut Saja',
      };
    }
  }

  if (norm === RO_TYPES.JASA_ANGKUT_MATERIAL) {
    const manualItems = items.filter((it) => !it.isAutoGenerated);
    if (manualItems.length === 0) {
      return {
        isValid: false,
        error: 'Harus memilih minimal 1 item Material',
      };
    }
    const invalidManual = manualItems.some((it) => getItemType(it) !== ITEM_TYPES.MATERIAL);
    if (invalidManual) {
      return {
        isValid: false,
        error: 'Hanya item Material yang boleh dipilih pada RO jenis Jasa Angkut + Material',
      };
    }
  }

  return { isValid: true, error: null };
}
