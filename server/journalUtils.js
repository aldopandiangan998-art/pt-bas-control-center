import { ITEM_TYPES, RO_TYPES, getItemType, normalizeRoType } from './roRules.js';

/**
 * Return date formatted as YYYY-MM-DD in WIB (Asia/Jakarta, UTC+7).
 */
export function getWibDateString(dateInput = new Date()) {
  const d = dateInput instanceof Date ? dateInput : new Date(dateInput);
  if (isNaN(d.getTime())) return '';
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Jakarta',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(d);
}

/**
 * Parse JSON items field safely into an array.
 */
export function parseRoItems(itemsRaw) {
  if (Array.isArray(itemsRaw)) return itemsRaw;
  if (typeof itemsRaw === 'string' && itemsRaw.trim()) {
    try {
      const parsed = JSON.parse(itemsRaw);
      return Array.isArray(parsed) ? parsed : [];
    } catch {
      return [];
    }
  }
  return [];
}

/**
 * Resolve unit pricing (hargaBeli, hargaJual, satuan) for a single GI
 * against the parent Received Order items and master materials fallback.
 */
export function resolveGiPricing(sj, po = null, materialsList = [], fallbackPrices = {}) {
  const matName = String(sj?.material || po?.materialName || '').trim();
  const matUpper = matName.toUpperCase();
  const roItems = parseRoItems(po?.items);
  const normRoType = normalizeRoType(po?.jenisRO || po?.jenis);
  const isJasaOnly = normRoType === RO_TYPES.JASA_ANGKUT_SAJA;

  // Match against RO items first (prefer manual primary items over auto-generated Jasa Angkut)
  const candidateItems = isJasaOnly
    ? roItems
    : roItems.filter((it) => !it.isAutoGenerated && getItemType(it) !== ITEM_TYPES.JASA_ANGKUT);

  const matchedRoItem =
    candidateItems.find((it) => String(it.nama || it.name || '').trim().toUpperCase() === matUpper) ||
    roItems.find((it) => String(it.nama || it.name || '').trim().toUpperCase() === matUpper) ||
    null;

  const matchedMasterMat =
    (materialsList || []).find((m) => String(m.name || m.nama || '').trim().toUpperCase() === matUpper) ||
    null;

  const hargaBeli = Number(
    matchedRoItem?.hargaBeli ??
      (matUpper && po?.materialName && String(po.materialName).trim().toUpperCase() === matUpper ? po.hargaBeli : undefined) ??
      matchedMasterMat?.beli ??
      po?.hargaBeli ??
      fallbackPrices.hargaBeli ??
      0
  ) || 0;

  const hargaJual = Number(
    matchedRoItem?.hargaJual ??
      (matUpper && po?.materialName && String(po.materialName).trim().toUpperCase() === matUpper ? po.hargaJual : undefined) ??
      matchedMasterMat?.jual ??
      po?.hargaJual ??
      fallbackPrices.hargaJual ??
      0
  ) || 0;

  const satuan =
    matchedRoItem?.satuan ||
    matchedMasterMat?.defaultUnit ||
    matchedMasterMat?.satuan ||
    po?.satuan ||
    fallbackPrices.satuan ||
    'm3';

  return { hargaBeli, hargaJual, satuan };
}

/**
 * Build normalized suratJalanDetails, multi-material itemsSummary, and financial totals
 * for a daily Jurnal GI from its linked Surat Jalan rows.
 */
export function aggregateJournalWaybills({
  sjs = [],
  jurnal,
  po = null,
  materialsList = [],
  cumulativeVol = null,
}) {
  const fallbackPrices = {
    hargaBeli: Number(jurnal?.hargaBeli) || 0,
    hargaJual: Number(jurnal?.hargaJual) || 0,
    satuan: jurnal?.satuan || 'm3',
  };

  const suratJalanDetails = [];
  const summaryMap = {};
  let totalVolumeRaw = 0;
  let totalNominalBeli = 0;
  let totalNominalJual = 0;

  for (const sj of sjs) {
    const vol = Number(sj.volumeAkhir) || 0;
    const { hargaBeli, hargaJual, satuan } = resolveGiPricing(sj, po, materialsList, fallbackPrices);
    const nomBeli = Math.round(vol * hargaBeli);
    const nomJual = Math.round(vol * hargaJual);

    totalVolumeRaw += vol;
    totalNominalBeli += nomBeli;
    totalNominalJual += nomJual;

    const matLabel = sj.material || jurnal?.material || po?.materialName || 'MATERIAL';
    if (!summaryMap[matLabel]) {
      summaryMap[matLabel] = {
        material: matLabel,
        satuan,
        ritase: 0,
        count: 0,
        volume: 0,
        hargaBeli,
        hargaJual,
        nominalBeli: 0,
        nominalJual: 0,
      };
    }
    summaryMap[matLabel].ritase += 1;
    summaryMap[matLabel].count += 1;
    summaryMap[matLabel].volume = Number((summaryMap[matLabel].volume + vol).toFixed(2));
    summaryMap[matLabel].nominalBeli += nomBeli;
    summaryMap[matLabel].nominalJual += nomJual;

    suratJalanDetails.push({
      id: sj.id,
      poNumber: sj.poNumber || jurnal?.poNumber || po?.nomorPo || null,
      nomorRO: jurnal?.nomorRO || sj.nomorRO || po?.nomorRO || '',
      jurnalId: jurnal?.id,
      customer: sj.customer || jurnal?.customer || po?.customer || '',
      material: matLabel,
      satuan,
      hargaBeli,
      hargaJual,
      nominalBeli: nomBeli,
      nominalJual: nomJual,
      nopol: sj.nopol || 'W 9821 UB',
      driver: sj.driver || 'Supir Armada Terjadwal',
      tanggal: sj.tanggalDibuat || sj.tanggal,
      tanggalDibuat: sj.tanggalDibuat || sj.tanggal,
      tanggalJadwal: sj.tanggalJadwal || sj.tanggal,
      waktu: sj.waktu || '09:00',
      nomorNota: sj.nomorNota || '',
      panjangCm: Number(sj.panjangCm) || 0,
      lebarCm: Number(sj.lebarCm) || 0,
      tinggiCm: Number(sj.tinggiCm) || 0,
      koreksiTinggiCm: Number(sj.koreksiTinggiCm) || 0,
      volumeAkhir: vol,
      status: sj.status || 'Selesai',
    });
  }

  const itemsSummary = Object.values(summaryMap);
  const totalSj = suratJalanDetails.length;
  const totalVolume = Number(totalVolumeRaw.toFixed(2));
  const distinctMaterials = itemsSummary.map((i) => i.material).filter(Boolean);
  const materialLabel =
    distinctMaterials.length > 0
      ? distinctMaterials.join(', ')
      : (jurnal?.material || po?.materialName || 'SIRTU');

  const targetVol = Number(jurnal?.targetVolume ?? po?.totalOrder ?? 0) || 0;
  const effectiveCumulative = cumulativeVol !== null && cumulativeVol !== undefined ? Number(cumulativeVol) : totalVolume;
  const status = targetVol > 0 && effectiveCumulative >= targetVol ? 'Selesai Kirim' : 'Dalam Pengiriman';

  return {
    suratJalanDetails,
    itemsSummary,
    materialLabel,
    totalSj,
    totalVolume,
    nominalBeli: totalNominalBeli,
    nominalJual: totalNominalJual,
    status,
  };
}
